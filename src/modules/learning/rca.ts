const points = {
  map: ["K01", "O1"],
  problem: ["K02", "O1"],
  process: ["K03", "O1"],
  evidence: ["K04", "O2"],
  layers: ["K05", "O2"],
  actions: ["K06", "O3"],
  validation: ["K07", "O4"],
  closure: ["K08", "O4"],
} as const;

type Distractor = [label: string, misconception: string, explanation: string];

function q(
  id: string,
  key: keyof typeof cards,
  level: Question["level"],
  prompt: string,
  right: [label: string, explanation: string],
  wrong: [Distractor, Distractor],
  correct: number,
): Question {
  const [knowledge, objective] = points[key];
  const options: Question["options"] = wrong.map(
    ([label, misconception, explanation]) => ({
      label,
      misconception,
      explanation,
    }),
  );
  options.splice(correct, 0, { label: right[0], explanation: right[1] });
  return {
    id,
    knowledge,
    objective,
    card: cards[key].id,
    level,
    prompt,
    options,
    correct,
    difficulty: level < 3 ? "基础" : "进阶",
  };
}

