const headingPatterns = [
  /真正导致问题/,
  /RCA\s*的基本框架/,
  /先把.*问题/,
  /跳过.*Process/,
  /Possible Cause.*Root Cause/,
  /Problem Symptom/,
  /Containment.*Corrective Action/,
  /Action.*Cause.*对得上/,
  /Action Completed.*Problem Solved/,
  /Review RCA.*五个/,
  /只记住这条主线|一句话总结/,
  /图解.*RCA/,
];

export function getRcaReferenceAnchors(toc: { id: string; text: string }[]) {
  return Object.fromEntries(
    headingPatterns.flatMap((pattern, index) => {
      const heading = toc.find(({ text }) => pattern.test(text));
      return heading ? [[index, heading.id]] : [];
    }),
  );
}
