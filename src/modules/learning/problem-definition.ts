export function getProblemDefinitionAnchors(
  toc: { id: string; text: string }[],
) {
  const anchors: Record<number, string> = {};
  for (const { id, text } of toc) {
    const section = Number(text.match(/^\s*(\d{1,2})\s*[.．、]/)?.[1]);
    if (section >= 1 && section <= 14) anchors[section] ??= id;
    if (/先把问题描述清楚/.test(text)) anchors[0] ??= id;
    if (/最后.*四件事|一句话总结/.test(text)) anchors[15] ??= id;
    if (/图解.*定义问题/.test(text)) anchors[16] ??= id;
  }
  return anchors;
}
